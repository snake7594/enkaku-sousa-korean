def read_tsv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def write_tsv(path: Path, rows: list[dict[str, str]]) -> None:
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=["offset", "lines", "text"],
            delimiter="\t",
            lineterminator="\n",
        )
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    source = read_tsv(SOURCE)
    rows = read_tsv(TARGET)
    assert len(source) == len(rows) == 9626
    assert set(MANUAL) == set(range(6301, 6401))

    changes: list[dict[str, object]] = []
    for order, new_text in MANUAL.items():
        old_text = rows[order]["text"]
        rows[order]["text"] = new_text
        rows[order]["lines"] = str(new_text.count(r"\n") + 1)
        changes.append(
            {
                "order": order,
                "offset": rows[order]["offset"],
                "source_ja": source[order]["text"],
                "old_translation": old_text,
                "new_translation": new_text,
                "status": "manual_context_retranslation",
                "emulator_launched": False,
            }
        )

    write_tsv(TARGET, rows)
    REPORT.write_text(
        json.dumps(
            {
                "schema": "enkaku_retranslation_v2_manual_rest_report",
                "source_range": {"order_start": 6301, "order_end": 6400, "count": 100},
                "rows": len(rows),
                "changed": len(changes),
                "translations": changes,
                "emulator_launched": False,
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print(json.dumps({"rows": len(rows), "changed": len(changes), "emulator_launched": False}, ensure_ascii=False))


if __name__ == "__main__":
    main()
