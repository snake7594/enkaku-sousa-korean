            "원문의 정보와 제어용 줄바꿈을 보존하고 누락·임의 추가를 금지",
            "손상된 한자는 source_ja_reviewed에 복원 가설과 불확실성을 기록",
            "대사 본문은 프로젝트 기준 폭 19자에 맞춰 의미 단위로 추가 줄바꿈",
