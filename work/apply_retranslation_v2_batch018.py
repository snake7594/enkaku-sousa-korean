    with path.open('w', encoding='utf-8', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=['offset', 'lines', 'text'], delimiter='\t', lineterminator='\n')
        writer.writeheader()
        writer.writerows(rows)


