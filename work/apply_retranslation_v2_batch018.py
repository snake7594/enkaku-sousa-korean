            '미우라의 유죄율 설명은 법률 용어를 과장하지 않고 심문 압박의 기능이 드러나도록 번역',
            '미야카미 긴자, 무허가 택시, 아사츠유의 증언을 하나의 알리바이 논리로 유지',
