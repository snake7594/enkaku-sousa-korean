def normalize_scoped_phrase_rows(items: list[dict]) -> list[dict]:
    """Resolve mixed historical row numbering to actual zero-based TSV rows.

    The evidence lists were collected at different stages, some with the TSV
    header included and some without it.  For each declared row, retain the
    adjacent candidate(s) whose raw text actually contains the exact token
    pattern.  This keeps the ledger reproducible while avoiding silent
    off-by-one repairs in script_full_ja.tsv.
    """
    with RAW.open(encoding="utf-8-sig", newline="") as fh:
        raw_rows = list(csv.DictReader(fh, delimiter="\t"))
    normalized: list[dict] = []
    for original in items:
        item = dict(original)
        pattern = item.get("raw_pattern", "")
        targets: set[int] = set()
        for value in item.get("raw_row_indices", []):
            value = int(value)
            for candidate in (value - 1, value):
                if 0 <= candidate < len(raw_rows) and pattern in raw_rows[candidate]["text"]:
                    targets.add(candidate)
        item["raw_row_indices"] = sorted(targets)
        item["row_index_basis"] = "zero_based_script_full_raw.tsv_data_rows"
        normalized.append(item)
    return normalized


