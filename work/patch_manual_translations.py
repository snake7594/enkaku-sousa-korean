def main() -> None:
    data = json.loads(TARGET.read_text(encoding="utf-8"))
    by_order = data.setdefault("by_order", {})
    for order, update in UPDATES.items():
        entry = by_order.setdefault(order, {})
        entry.update(update)
    TARGET.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"patched manual translations: {len(UPDATES)}")


if __name__ == "__main__":
    main()
